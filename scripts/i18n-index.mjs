// Writes src/messages/<locale>/index.ts: imports every namespace file (src/messages/<locale>/<namespace>.json) and
// exports them as one messages object for next-intl. Run after adding a namespace file: npm run i18n:index
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../src/messages")
const id = (ns) => ns.replace(/[^a-zA-Z0-9]/g, "_")

for (const locale of ["en", "km"]) {
  const names = fs
    .readdirSync(path.join(dir, locale))
    .filter((f) => f.endsWith(".json"))
    .map((f) => f.slice(0, -5))
    .sort()
  const out =
    `// Generated by \`npm run i18n:index\`: one JSON file per namespace (src/messages/${locale}/<namespace>.json).\n` +
    `// Edit the JSON files, not this file. Add a namespace by creating its JSON file in en/ and km/, then run the script.\n` +
    names.map((ns) => `import ${id(ns)} from "./${ns}.json"`).join("\n") +
    `\n\nconst messages = {\n` +
    names.map((ns) => `  ${JSON.stringify(ns)}: ${id(ns)},`).join("\n") +
    `\n}\n\nexport default messages\n`
  const file = path.join(dir, locale, "index.ts")
  if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== out) fs.writeFileSync(file, out)
  console.log(`${locale}: ${names.length} namespaces`)
}
