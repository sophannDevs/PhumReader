package app.phumreader.seed;

import java.math.BigDecimal;
import java.math.RoundingMode;
import java.nio.charset.StandardCharsets;
import java.time.Duration;
import java.time.LocalDate;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.UUID;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * The website's demo rules, ported so the seeded database shows the same numbers as the demo:
 * episode generation ({@code generateEpisodes} in src/data/selectors.ts), count parsing ({@code
 * parseCount} in src/lib/format.ts) and the genre slug ({@code genreSlug} in src/lib/routes.ts).
 */
final class DemoRules {

    /** The demo creator whose series the website's creator dashboard shows (demo-api.ts). */
    static final String STAND_IN_CREATOR = "Chan Sreyleak";

    /** The first comics in the ranking, in this order (src/data/selectors.ts, Assumption 4). */
    static final List<String> HOME_COMICS =
            List.of(
                    "Paper Tigers",
                    "Neon Monsoon",
                    "Tiny Dragon Café",
                    "The Orchard Pact",
                    "Summer Index",
                    "Ember & Co.",
                    "Captain Nobody",
                    "Salt & Thunder");

    /** Subscribers are not in the demo data: about 4.68% of likes (Assumption 5). */
    static final double SUBSCRIBERS_PER_LIKE = 0.04683;

    private static final Pattern COUNT =
            Pattern.compile("^([\\d.,]+)\\s*([KMB])?$", Pattern.CASE_INSENSITIVE);
    private static final Pattern AGO = Pattern.compile("^(\\d+)\\s*([mhdw])$");
    private static final DateTimeFormatter DISPLAY_DATE =
            DateTimeFormatter.ofPattern("MMM d, yyyy", Locale.US);
    private static final Map<String, String> WEEKDAYS =
            Map.of(
                    "Mon", "MONDAY",
                    "Tue", "TUESDAY",
                    "Wed", "WEDNESDAY",
                    "Thu", "THURSDAY",
                    "Fri", "FRIDAY",
                    "Sat", "SATURDAY",
                    "Sun", "SUNDAY");

    private DemoRules() {}

    /** One episode or chapter as the demo shows it. */
    record SeedEpisode(
            int number, String title, LocalDate date, long likes, String thumb, boolean fastPass) {}

    /** "1.6M" → 1600000, "871K" → 871000, "412" → 412; anything else → 0. */
    static long parseCount(String text) {
        Matcher m = COUNT.matcher(text.trim());
        if (!m.matches()) {
            return 0;
        }
        BigDecimal value = new BigDecimal(m.group(1).replace(",", ""));
        String unit = m.group(2) == null ? "" : m.group(2).toUpperCase(Locale.ROOT);
        BigDecimal multiplier =
                switch (unit) {
                    case "K" -> BigDecimal.valueOf(1_000);
                    case "M" -> BigDecimal.valueOf(1_000_000);
                    case "B" -> BigDecimal.valueOf(1_000_000_000);
                    default -> BigDecimal.ONE;
                };
        return value.multiply(multiplier).setScale(0, RoundingMode.HALF_UP).longValueExact();
    }

    /** "2h" → 2 hours, "1d" → 1 day; unknown → zero. */
    static Duration parseAgo(String when) {
        Matcher m = AGO.matcher(when.trim());
        if (!m.matches()) {
            return Duration.ZERO;
        }
        long n = Long.parseLong(m.group(1));
        return switch (m.group(2)) {
            case "m" -> Duration.ofMinutes(n);
            case "h" -> Duration.ofHours(n);
            case "d" -> Duration.ofDays(n);
            default -> Duration.ofDays(7 * n);
        };
    }

    /** "Slice of life" → "slice-of-life", "Sci-fi" → "sci-fi". */
    static String genreSlug(String genre) {
        return genre.toLowerCase(Locale.ROOT).replaceAll("\\s+", "-");
    }

    /** "Pich & Co." → "pich-co" (for seeded e-mail addresses). */
    static String slug(String text) {
        return text.toLowerCase(Locale.ROOT).replaceAll("[^a-z0-9]+", "-").replaceAll("^-|-$", "");
    }

    /** "Mon" → "MONDAY". */
    static String weekday(String shortName) {
        String day = WEEKDAYS.get(shortName);
        if (day == null) {
            throw new IllegalArgumentException("Unknown weekday: " + shortName);
        }
        return day;
    }

    /** Stable ids, so seeding twice finds the rows it made the first time. */
    static UUID id(String kind, String key) {
        return UUID.nameUUIDFromBytes(
                ("phumreader-demo:" + kind + ":" + key).getBytes(StandardCharsets.UTF_8));
    }

    /**
     * All episodes of a series, oldest first: the hand-written sample, or generated by the rule.
     */
    static List<SeedEpisode> episodes(DemoData data, DemoData.Series series) {
        List<DemoData.Episode> sample = data.episodesSample().get(series.slug());
        if (sample != null) {
            return sample.stream()
                    .map(e ->
                            new SeedEpisode(
                                    e.n(),
                                    e.title(),
                                    LocalDate.parse(e.date(), DISPLAY_DATE),
                                    parseCount(e.likes()),
                                    e.thumb(),
                                    "fastpass".equals(e.access())))
                    .toList();
        }
        return generate(data, series);
    }

    /** Port of generateEpisodes() in src/data/selectors.ts: same numbers, dates and titles. */
    private static List<SeedEpisode> generate(DemoData data, DemoData.Series series) {
        List<String> thumbs =
                data.episodesSample().get("glass-compass").stream()
                        .map(DemoData.Episode::thumb)
                        .toList();
        List<String> names = data.chapterNames();
        int free = series.freeEpisodes();
        double base = 40 + (hash(series.id()) % 100) / 10.0;
        List<SeedEpisode> episodes = new ArrayList<>();
        for (int n = 1; n <= free + series.fastPassEpisodes(); n++) {
            boolean fast = n > free;
            LocalDate date =
                    fast
                            ? data.today().plusDays(7L * (n - free))
                            : data.today().minusDays(7L * (free - n));
            int group = (n - 1) / 5;
            int step = (n - 1) % 5;
            double thousands =
                    fast ? base * 0.48 + 0.8 * (n - free - 1) : base + 0.1 * group + 0.825 * step;
            long likes = Math.round(thousands * 10) * 100;
            String name = names.get(n % names.size());
            String title =
                    "novel".equals(series.type())
                            ? "Chapter " + n + ": " + name
                            : n >= 80 ? "(S2) Episode " + n : "Episode " + n;
            episodes.add(
                    new SeedEpisode(
                            n, title, date, likes, thumbs.get((n - 1) % thumbs.size()), fast));
        }
        return episodes;
    }

    /** The website's string hash: h = (h * 31 + charCode) as an unsigned 32-bit number. */
    static long hash(String text) {
        long h = 0;
        for (int i = 0; i < text.length(); i++) {
            h = (h * 31 + text.charAt(i)) & 0xFFFF_FFFFL;
        }
        return h;
    }
}
